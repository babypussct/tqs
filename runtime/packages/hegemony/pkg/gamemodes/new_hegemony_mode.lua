local heg_description = [==[
# 国战简介

《三国杀·国战》是一款可以支持2\~12人(线上版4\~8人)同时参与的桌面卡牌游戏。在游戏中，每名玩家将甄选三国时代中包括魏国、蜀国、吴国、群雄在内的各位名将，组成自己的战斗团队，利用他们珠联璧合的组合技能发起进攻，消灭其他各方势力，赢得最终的胜利。

## 游戏目标

消灭与自己势力不同的所有角色：野心家消灭所有其他角色，包括其他野心家。

## 游戏准备

**挑选武将：**

每名玩家分发若干张武将牌，挑选势力相同的两张武将牌背面向上放置，称为“暗置”。左侧为主将，右侧为副将。

**分发体力牌：**

体力上限为两张武将牌阴阳鱼数量之和。两个“半个阴阳鱼”可以组成一个完整的阴阳鱼。两张武将牌首次均明置后，若有未组成完整阴阳鱼的“半个阴阳鱼”，该角色获得一个“阴阳鱼”标记。

**分发起始手牌：**

将游戏牌混洗，发给每名玩家四张起始手牌，剩余游戏牌作为牌堆。

## 游戏开始

由起始玩家开始，所有玩家按逆时针方向依次进行各自的回合，每个回合包含四个阶段和回合开始时与回合结束时两个特殊时点，按以下顺序执行：

回合开始时→判定阶段→摸牌阶段→出牌阶段→弃牌阶段→回合结束时

不同武将同一阶段或时点若存在多个可发动技能，由正在进行回合的玩家开始，所有玩家按逆时针方向依次选择是否发动技能。

同一武将同一阶段或时点存在多个可发动技能，按任意顺序依次选择是否发动这些技能。

## 暗将规则

暗置武将牌没有技能、性别、势力，发动技能须将武将牌翻开，称为“明置”，然后发动该武将技能：每局游戏第一个明置武将牌的角色获得一个“先驱”标记。

除发动技能外，以下两种方式可以主动明置武将牌：
1.有“锁定技”的武将于其出牌阶段可以主动明置此武将牌；
2.每名玩家于自己的回合开始时，可以明置一至两张武将牌。

若武将牌均明置，性别以主将为准。

在新月杀中，你需要“预亮”某些触发技，即点击技能到“预亮”状态，来让系统在相应的时机询问你是否发动技能亮将。不“预亮”的技能不会询问。

## 野心家规则

一名角色首次明置武将牌时，其势力阵亡与存活的角色数之和若至少为游戏总角色数的一半，向下取整，该角色成为野心家：一名角色因明置武将牌成为野心家或明置野心家武将后，其获得一个“野心家”标记。

## 击杀奖惩

野心家杀死一名角色，摸三张牌；

未明确势力的角色杀死一名角色不执行奖惩；

明确势力的角色杀死与其势力相同的角色，须弃置装备区和手牌区里的所有牌；

明确势力的角色杀死与其势力不同的角色，摸等同于该势力存活角色数的牌，包括此次被杀死的角色。

未明确势力的角色被杀死时，须明置其所有武将牌确认势力。

## 鏖战规则

一名角色的回合开始时，若场上存活的角色数不大于游戏总角色数的一半，向下取整，且场上没有势力相同的角色，游戏进入鏖战模式直到游戏结束。

（鏖战规则2019版）【桃】只能当【杀】、【闪】使用或打出，不能回复体力。

（鏖战规则2026版）【桃】只能当【酒】使用或打出。

## 珠联璧合

珠联璧合表示了部分武将之间的特殊联系。一般是夫妻、挚友等，如刘备-关羽，周瑜-小乔。

表示武将之间的关联，武将牌右下方显示的其他武将与此武将牌形成珠联璧合，一名角色首次将两张形成珠联壁合的武将牌均明置后，其获得一个“珠联壁合”标记。

## 标记牌

**珠联璧合**：出牌阶段，你可弃一枚“珠联璧合”，摸两张牌；你可弃一枚“珠联璧合”，视为使用【桃】。

**阴阳鱼**：出牌阶段，你可弃一枚“阴阳鱼”，摸一张牌；弃牌阶段开始时，你可弃一枚“阴阳鱼”，此回合手牌上限+2。

**先驱**：出牌阶段，你可弃一枚“先驱”，将手牌摸至4张，观看一名其他角色的一张暗置武将牌。

## 移出游戏（势备篇）

被移出游戏的角色所有技能失效，体力值不会改变，不计入距离和座次计算，不能使用牌且不是牌和技能的合法目标；移出游戏不会影响场上存活角色数与势力角色数计算。

## 合纵 （势备篇）

某些牌上标有“合”标记。

每名角色的出牌阶段限一次，可以选择一项：
1.若你已确定势力，你可以将手牌中有“合”标记的至多三张牌交给与你势力不同的一名角色，摸等量的牌。
2.你可以将手牌中有“合”标记的至多三张牌交给未确定势力的一名角色。

即，出限一、限三张、摸等量。给明将摸牌，给暗将不摸；暗将不能给明将。

## 奇珍牌 （九变篇）

九变篇中的装备牌均为奇珍牌。装备区内拥有奇珍牌的角色，受到【杀】造成的伤害后，伤害来源可以获得其装备区的一张奇珍牌。

## 阵法技 （君临天下·阵）

**阵法技**：拥有阵法技的角色处于阵法关系时锁定生效的技能，该类角色可以在其出牌阶段发起“阵法召唤”，出牌阶段限一次，拥有阵法技的角色发起，满足此阵法关系的未明确势力角色均可按逆时针顺序依次明置一张与发起角色势力相同的武将牌，使阵法技生效。

**围攻**：阵法关系，一名角色的上家和下家势力相同且与该角色势力不同，该角色为“被围攻角色”，其上家和下家为“围攻角色”，这三名角色处于同一“围攻关系”。

**队列**：阵法关系，至少两名势力相同的角色连续相邻，这些角色处于同一“队列”。

**对垒**：阵法关系，一名角色的对家已明确势力且与其势力不同，这两名角色互为“对垒”。

**主将技**：此武将牌为主将时才能使用的技能。

**副将技**：此武将牌为副武将才能使用的技能。

## 移除 （君临天下·势）

**移除**：被移除的武将牌视为未加入游戏，移除此武将牌的角色用“士兵”代替被移除的武将牌，“士兵”没有技能，性别、势力与被移除的武将牌相同，移除武将牌不会影响该角色的体力上限。

## 变更 （君临天下·变）

**变更**：从随机的三个同势力武将中选择一个，作为新的副将替换被变更的武将牌，变更武将不会影响体力上限，不会形成珠联壁合或因“半个阴阳鱼”获得标记，一旦开始变更武将，则必须替换被变更的武将，此武将牌视为未加入游戏。

## 军令 （君临天下·权）

**军令**：发起“军令”的角色抽取两张军令牌，选择其中一张交给执行“军令”的角色，该角色选择是否执行此“军令”，执行则立即结算军令牌的效果。

军令一：对发起者指定的角色造成1点伤害；

军令二：摸一张牌，然后交给发起者两张牌；

军令三：失去1点体力；

军令四：本回合不能使用或打出手牌且所有非锁定技失效；

军令五：叠置，本回合不能回复体力；

军令六：选择一张手牌和一张装备区里的牌，弃置其余的牌。

## 大势力、小势力 （势备篇）

场上存活且明确势力的角色中，角色数最多且不小于2的势力为大势力，场上可以同时存在多个大势力，不为大势力的角色，包括未明确势力的角色均为小势力，若场上没有大势力，则不存在小势力。

## 君主规则 （君临天下）

势力为“君”的武将为该势力君主武将，玩家在自己的第一个回合开始时，若主将为君主武将的同名武将且未明置，则可以明置此武将牌并替换为同名君主武将，若因此增加体力上限，则回复1点体力，君主武将明置后不能被暗置。

君主明置后，与其势力相同的野心家恢复原势力，不再视为野心家。

君主存活时，与其势力相同的角色不会成为野心家。

君主死亡后，与其势力相同的其他角色均视为野心家。

## 双势力武将 （不臣篇）

有两个势力的武将为双势力武将，双势力武将不能作为主将，仅能作为副将，且其中一个势力须与主将势力相同，双势力武将明置时，若主将未明置，则须声明主将势力，遵守该势力胜利条件。

## 势力锦囊 （不臣篇）

若势力锦囊的使用者已明确势力，且与该势力锦囊相同，则获得该势力锦囊额外效果，否则仅能执行基础效果，势力锦囊置入弃牌堆后移出游戏；不能转化势力锦囊。

## 野心家武将 （不臣篇）

势力为“野”的武将为野心家武将，野心家武将仅能作为主将，不能作为副将，可以搭配野心家及君主以外的任何武将，选择野心家武将即视为野心家，遵守野心家胜利条件，若野心家武将未明置过，则仅明置副将时势力以副将为准，野心家武将明置后，本局游戏视为野心家，不受君主影响，若副将为双势力武将，则仅明置副将时，也视为野心家。

## 暴露野心 （不臣篇）

游戏触发胜利条件时，若场上有未明置过的野心家武将，则需明置此武将牌，成为野心家继续进行游戏，否则视为游戏失败。

## 休整 （线下）

休整的角色将移出游戏，但该角色仍视为存活。在休整时间结束时，该角色将移回游戏并回复全部体力。

## 神武将 （线下）

神将单独明置时任选势力。当主将或副将存在有势力的武将明置时，以该武将的势力为准。主副将均为神将时，以后明置的神将势力为准。

